import type { AuditReport } from "./types";

const L = {
  en: {
    title: "AI visibility report", score: "Score", grade: "Grade", site: "Site average", date: "Audited",
    issues: "Issues to fix", passed: "Passing checks", bots: "AI crawler access", bot: "Agent", vendor: "Used by",
    access: "Access", allowed: "allowed", blocked: "blocked", pages: "Pages scanned", page: "Page",
    fix: "Fix", files: "Generated fixes", footer: "Generated by Quovra, the open-source GEO toolkit.",
  },
  tr: {
    title: "Yapay zekâ görünürlük raporu", score: "Puan", grade: "Not", site: "Site ortalaması", date: "Denetim tarihi",
    issues: "Düzeltilmesi gerekenler", passed: "Geçen kontroller", bots: "Yapay zekâ botu erişimi", bot: "Bot", vendor: "Kullanan",
    access: "Erişim", allowed: "izinli", blocked: "engelli", pages: "Taranan sayfalar", page: "Sayfa",
    fix: "Çözüm", files: "Hazır düzeltmeler", footer: "Açık kaynak GEO aracı Quovra ile oluşturuldu.",
  },
};

/** Renders an audit as a Markdown document for sharing with clients or teammates. */
export function toMarkdown(r: AuditReport): string {
  const t = L[r.lang];
  const host = new URL(r.finalUrl).hostname;
  const issues = r.checks.filter((c) => c.status !== "pass");
  const out = [
    `# ${t.title}: ${host}`,
    "",
    `**${t.score}: ${r.score}/100** · **${t.grade}: ${r.grade}**${r.siteScore !== undefined ? ` · ${t.site}: ${r.siteScore}/100` : ""}  `,
    `${t.date}: ${r.fetchedAt.slice(0, 10)} · ${r.finalUrl}`,
    "",
    `## ${t.issues} (${issues.length})`,
    "",
    ...issues.flatMap((c) => [
      `### ${c.status === "fail" ? "🔴" : "🟠"} ${c.title} (${c.score}/${c.weight})`,
      "",
      c.detail,
      "",
      ...(c.fix ? [`**${t.fix}:** ${c.fix}`, ""] : []),
    ]),
    `## ${t.passed}`,
    "",
    ...r.checks.filter((c) => c.status === "pass").map((c) => `- ✅ ${c.title}`),
    "",
    `## ${t.bots}`,
    "",
    `| ${t.bot} | ${t.vendor} | ${t.access} |`,
    "| --- | --- | --- |",
    ...r.bots.map((b) => `| \`${b.bot}\` | ${b.vendor} | ${b.allowed ? t.allowed : `**${t.blocked}**`} |`),
    "",
  ];
  if (r.pages?.length) {
    out.push(`## ${t.pages}`, "", `| ${t.page} | ${t.score} | ${t.issues} |`, "| --- | --- | --- |");
    for (const p of r.pages) out.push(`| ${p.url} | ${p.status ? `${p.score} (${p.grade})` : "–"} | ${p.issues.slice(0, 3).join("; ")} |`);
    out.push("");
  }
  out.push(
    `## ${t.files}`, "",
    "### llms.txt", "", "```markdown", r.generated.llmsTxt.trimEnd(), "```", "",
    "### JSON-LD", "", "```html", r.generated.jsonLd, "```", "",
    "### robots.txt", "", "```", r.generated.robotsTxt.trimEnd(), "```", "",
    "---", `_${t.footer}_`, "",
  );
  return out.join("\n");
}
